async function seedDocument(collection, id, fields) {
  function encode(value) {
    if (value === null) return { nullValue: null };
    if (value instanceof Date) return { timestampValue: value.toISOString() };
    if (typeof value === 'boolean') return { booleanValue: value };
    if (typeof value === 'number') return { integerValue: String(value) };
    if (Array.isArray(value)) return { arrayValue: { values: value.map(encode) } };
    if (typeof value === 'object') return { mapValue: { fields: Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, encode(entry)])) } };
    return { stringValue: String(value) };
  }
  const encoded = {};
  for (const [key, value] of Object.entries(fields)) encoded[key] = encode(value);
  const params = new URLSearchParams();
  for (const key of Object.keys(fields)) params.append('updateMask.fieldPaths', key);
  const response = await fetch(`http://127.0.0.1:8088/v1/projects/${projectId}/databases/(default)/documents/${collection}/${id}?${params}`, {
    method: 'PATCH', headers: { Authorization: 'Bearer owner', 'Content-Type': 'application/json' }, body: JSON.stringify({ fields: encoded }),
  });
  assert(response.ok, `Emulator seed failed: ${await response.text()}`);
}
